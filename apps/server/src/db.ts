import { Pool, types } from 'pg';

types.setTypeParser(20, (value) => {
  const number = Number(value);
  if (!Number.isSafeInteger(number)) throw new RangeError('PostgreSQL BIGINT exceeds JavaScript safe integer range');
  return number;
});

export async function openDatabase(connectionString = process.env.DATABASE_URL): Promise<Pool> {
  if (!connectionString) throw new Error('DATABASE_URL is required');
  const db = new Pool({ connectionString, connectionTimeoutMillis: 5_000 });
  try {
    await migrate(db);
    return db;
  } catch (error) {
    await db.end();
    throw error;
  }
}

export async function schemaVersion(db: Pool): Promise<number> {
  const result = await db.query<{ version: number }>('SELECT version FROM schema_migrations ORDER BY version DESC LIMIT 1');
  return result.rows[0].version;
}

export async function migrate(db: Pool): Promise<void> {
  const client = await db.connect();
  try {
    await client.query('BEGIN');
    await client.query('SELECT pg_advisory_xact_lock(20261105)');
    await client.query('CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY)');
    const version = await client.query('SELECT version FROM schema_migrations WHERE version = 1');
    if (version.rowCount === 0) {
      await client.query(`

        CREATE TABLE jars (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL UNIQUE,
          kind TEXT NOT NULL CHECK (kind IN ('spending', 'saving')),
          parent_id INTEGER REFERENCES jars(id), monthly_budget BIGINT CHECK (monthly_budget >= 0),
          opening_balance BIGINT NOT NULL DEFAULT 0 CHECK (opening_balance >= 0),
          archived BOOLEAN NOT NULL DEFAULT FALSE,
          created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        );
        CREATE TABLE debts (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL,
          current_balance BIGINT CHECK (current_balance >= 0),
          expected_monthly BIGINT NOT NULL CHECK (expected_monthly > 0),
          due_day INTEGER CHECK (due_day BETWEEN 1 AND 31), interest_rate DOUBLE PRECISION,
          status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'paid_off')),
          created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        );
        CREATE TABLE recurring_templates (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL,
          kind TEXT NOT NULL CHECK (kind IN ('income', 'expense', 'transfer_to_saving', 'debt_payment')),
          jar_id INTEGER REFERENCES jars(id), debt_id INTEGER REFERENCES debts(id),
          frequency TEXT NOT NULL CHECK (frequency IN ('monthly', 'once', 'custom')),
          day_of_month INTEGER CHECK (day_of_month BETWEEN 1 AND 31),
          start_month TEXT NOT NULL, end_month TEXT,
          auto_repeat BOOLEAN NOT NULL, note TEXT,
          created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        );
        CREATE TABLE template_versions (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, template_id INTEGER NOT NULL REFERENCES recurring_templates(id),
          amount BIGINT NOT NULL CHECK (amount > 0), effective_from TEXT NOT NULL,
          created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
          UNIQUE (template_id, effective_from)
        );
        CREATE TABLE month_plans (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, month TEXT NOT NULL UNIQUE,
          status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
          closed_at TIMESTAMPTZ, snapshot_json JSONB,
          created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        );
        CREATE TABLE planned_items (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, month TEXT NOT NULL REFERENCES month_plans(month),
          template_id INTEGER REFERENCES recurring_templates(id), name TEXT NOT NULL,
          kind TEXT NOT NULL CHECK (kind IN ('income', 'expense', 'transfer_to_saving', 'debt_payment')),
          jar_id INTEGER REFERENCES jars(id), debt_id INTEGER REFERENCES debts(id),
          expected_amount BIGINT NOT NULL CHECK (expected_amount > 0),
          expected_day INTEGER CHECK (expected_day BETWEEN 1 AND 31),
          skipped BOOLEAN NOT NULL DEFAULT FALSE, note TEXT,
          is_overridden BOOLEAN NOT NULL DEFAULT FALSE,
          created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
          UNIQUE (month, template_id)
        );
        CREATE TABLE transactions (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, date TEXT NOT NULL,
          amount BIGINT NOT NULL CHECK (amount > 0),
          type TEXT NOT NULL CHECK (type IN ('income', 'expense', 'transfer_in', 'transfer_out')),
          jar_id INTEGER REFERENCES jars(id), planned_item_id INTEGER REFERENCES planned_items(id),
          description TEXT NOT NULL, note TEXT, deleted_at TIMESTAMPTZ,
          created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        );
        CREATE INDEX transactions_date_idx ON transactions(date) WHERE deleted_at IS NULL;
        CREATE TABLE settings (
          id INTEGER PRIMARY KEY CHECK (id = 1),
          account_opening_balance BIGINT NOT NULL DEFAULT 0,
          account_opening_date TEXT NOT NULL, schema_version INTEGER NOT NULL,
          created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        );
        INSERT INTO schema_migrations (version) VALUES (1);
      `);
    }
    // Migration 2: idempotency_key on transactions (non-destructive)
    const v2 = await client.query('SELECT version FROM schema_migrations WHERE version = 2');
    if (v2.rowCount === 0) {
      await client.query(`
        ALTER TABLE transactions ADD COLUMN IF NOT EXISTS idempotency_key TEXT;
        CREATE UNIQUE INDEX IF NOT EXISTS transactions_idempotency_key_idx
          ON transactions(idempotency_key) WHERE idempotency_key IS NOT NULL AND deleted_at IS NULL;
        INSERT INTO schema_migrations (version) VALUES (2);
      `);
    }

    const v3 = await client.query('SELECT version FROM schema_migrations WHERE version = 3');
    if (v3.rowCount === 0) {
      await client.query(`
        CREATE TABLE financial_targets (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          name TEXT NOT NULL,
          target_amount BIGINT NOT NULL CHECK (target_amount > 0),
          start_month TEXT NOT NULL,
          end_month TEXT NOT NULL,
          saving_jar_id INTEGER NOT NULL REFERENCES jars(id),
          created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
          updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        );
        INSERT INTO schema_migrations (version) VALUES (3);
      `);
    }

    const v4 = await client.query('SELECT version FROM schema_migrations WHERE version = 4');
    if (v4.rowCount === 0) {
      await client.query(`
        CREATE TABLE IF NOT EXISTS income_sources (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          name TEXT NOT NULL,
          archived BOOLEAN NOT NULL DEFAULT FALSE,
          created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
          updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        );
        CREATE UNIQUE INDEX IF NOT EXISTS income_sources_active_name_idx
          ON income_sources (LOWER(name)) WHERE archived = FALSE;
        ALTER TABLE transactions ADD COLUMN IF NOT EXISTS income_source_id INTEGER REFERENCES income_sources(id);
        INSERT INTO schema_migrations (version) VALUES (4);
      `);
    }

    const v5 = await client.query('SELECT version FROM schema_migrations WHERE version = 5');
    if (v5.rowCount === 0) {
      await client.query(`
        INSERT INTO income_sources (name) VALUES ('Lương'), ('Freelancer') ON CONFLICT DO NOTHING;
        INSERT INTO schema_migrations (version) VALUES (5);
      `);
    }
    const v6 = await client.query('SELECT version FROM schema_migrations WHERE version = 6');
    if (v6.rowCount === 0) {
      await client.query(`
        ALTER TABLE debts ALTER COLUMN expected_monthly DROP NOT NULL;
        INSERT INTO schema_migrations (version) VALUES (6);
      `);
    }
    const v7 = await client.query('SELECT version FROM schema_migrations WHERE version = 7');
    if (v7.rowCount === 0) {
      await client.query(`
        ALTER TABLE settings ADD COLUMN flexible_jar_id INTEGER REFERENCES jars(id);
        UPDATE jars SET name='Linh động', updated_at=NOW()
          WHERE name='Tiết kiệm chung' AND NOT EXISTS (SELECT 1 FROM jars WHERE name='Linh động');
        INSERT INTO jars (name,kind) SELECT 'Linh động','saving'
          WHERE EXISTS (SELECT 1 FROM settings)
            AND NOT EXISTS (SELECT 1 FROM jars WHERE name='Linh động' AND kind='saving');
        UPDATE jars SET archived=FALSE WHERE name='Linh động' AND kind='saving';
        UPDATE settings SET flexible_jar_id=(SELECT id FROM jars WHERE name='Linh động' AND kind='saving' LIMIT 1);
        ALTER TABLE financial_targets ALTER COLUMN start_month DROP NOT NULL;
        ALTER TABLE financial_targets ALTER COLUMN end_month DROP NOT NULL;
        ALTER TABLE financial_targets ALTER COLUMN saving_jar_id DROP NOT NULL;
        ALTER TABLE financial_targets ADD COLUMN sort_order INTEGER;
        UPDATE financial_targets SET sort_order=id;
        ALTER TABLE financial_targets ALTER COLUMN sort_order SET NOT NULL;
        ALTER TABLE financial_targets ADD COLUMN spent_at TEXT;
        ALTER TABLE financial_targets ADD COLUMN actual_amount BIGINT CHECK (actual_amount > 0);
        ALTER TABLE financial_targets ADD COLUMN withdrawal_txn_id INTEGER REFERENCES transactions(id);
        ALTER TABLE financial_targets ADD COLUMN expense_txn_id INTEGER REFERENCES transactions(id);
        INSERT INTO schema_migrations (version) VALUES (7);
      `);
    }
    const v8 = await client.query('SELECT version FROM schema_migrations WHERE version = 8');
    if (v8.rowCount === 0) {
      await client.query(`
        CREATE TABLE goals (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          type TEXT NOT NULL CHECK (type IN ('long', 'short')),
          parent_goal_id INTEGER REFERENCES goals(id) ON DELETE RESTRICT,
          title TEXT NOT NULL CHECK (BTRIM(title) <> ''), description TEXT NOT NULL DEFAULT '',
          start_date TEXT, due_date TEXT,
          status TEXT NOT NULL DEFAULT 'todo' CHECK (status IN ('todo', 'doing', 'done', 'paused')),
          created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        );
        CREATE TABLE checklist_items (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          goal_id INTEGER NOT NULL REFERENCES goals(id) ON DELETE CASCADE,
          title TEXT NOT NULL CHECK (BTRIM(title) <> ''), done BOOLEAN NOT NULL DEFAULT FALSE,
          created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        );
        CREATE TABLE journal_entries (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          datetime TIMESTAMPTZ NOT NULL,
          title TEXT NOT NULL CHECK (BTRIM(title) <> ''), content TEXT NOT NULL DEFAULT '',
          tags TEXT[] NOT NULL DEFAULT '{}',
          created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        );
        CREATE TABLE journal_goal_links (
          journal_id INTEGER NOT NULL REFERENCES journal_entries(id) ON DELETE CASCADE,
          goal_id INTEGER NOT NULL REFERENCES goals(id) ON DELETE CASCADE,
          PRIMARY KEY (journal_id, goal_id)
        );
        CREATE INDEX journal_entries_datetime_idx ON journal_entries(datetime DESC);
        INSERT INTO schema_migrations (version) VALUES (8);
      `);
    }
    const v9 = await client.query('SELECT version FROM schema_migrations WHERE version = 9');
    if (v9.rowCount === 0) {
      await client.query('UPDATE settings SET schema_version=9, updated_at=NOW()');
      await client.query('INSERT INTO schema_migrations (version) VALUES (9)');
    }

    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}
